let currentStage = 1; 
let questions = [];
let pathIndex = 0; 
let monsterIndex = 0; 
let currentQ = 0;
let score = 0;
let selectedHeroImg = "";

let totalSeconds = 90 * 60;
let timerInterval;

function shuffleArray(array) {
    for (let i = array.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [array[i], array[j]] = [array[j], array[i]];
    }
}

function selectHero(heroImg) {
    selectedHeroImg = heroImg;
    document.getElementById('selection-screen').classList.add('hidden');
    document.getElementById('section-screen').classList.remove('hidden');
    startTimer();
}

function startTimer() {
    timerInterval = setInterval(() => {
        if (totalSeconds <= 0) {
            clearInterval(timerInterval);
            alert("انتهى الوقت المخصص للعبة! ⌛");
            location.reload();
            return;
        }
        totalSeconds--;
        let hrs = Math.floor(totalSeconds / 3600);
        let mins = Math.floor((totalSeconds % 3600) / 60);
        let secs = totalSeconds % 60;
        document.getElementById('timer-display').innerText = 
            `⏳ الوقت: ${String(hrs).padStart(2, '0')}:${String(mins).padStart(2, '0')}:${String(secs).padStart(2, '0')}`;
    }, 1000);
}

function startStageGame() {
    document.getElementById('section-screen').classList.add('hidden');
    if (currentStage === 1) {
        questions = [...scienceQuestions];
        document.getElementById('stage-display').innerText = "📚 المرحلة: العلوم";
    } else if (currentStage === 2) {
        questions = [...mathQuestions];
        document.getElementById('stage-display').innerText = "📐 المرحلة: الرياضيات";
    } else {
        questions = [...readingQuestions];
        document.getElementById('stage-display').innerText = "📖 المرحلة: القراءة";
    }
    shuffleArray(questions);
    pathIndex = 0;
    monsterIndex = 0;
    currentQ = 0;
    createMaze();
}

function createMaze() {
    const grid = document.getElementById('maze-grid');
    grid.innerHTML = '';
    for (let r = 0; r < 12; r++) {
        for (let c = 0; c < 12; c++) {
            const div = document.createElement('div');
            div.classList.add('cell');
            if (mazeLayout[r][c] === 1) div.classList.add('wall');
            else if (mazeLayout[r][c] === 2) div.classList.add('exit-door');
            else div.classList.add('path');
            div.id = `cell-${r}-${c}`;
            grid.appendChild(div);
        }
    }
    updatePositions();
    loadQuestion();
}

function loadQuestion() {
    if (currentQ >= questions.length) {
        if (currentStage === 1) {
            currentStage = 2;
            document.getElementById('stage-title').innerText = "أحسنتِ! انتقلي الآن إلى المرحلة الثانية: متاهة الرياضيات";
            document.getElementById('section-screen').classList.remove('hidden');
            return;
        } else if (currentStage === 2) {
            currentStage = 3;
            document.getElementById('stage-title').innerText = "أحسنتِ! انتقلي الآن إلى المرحلة الثالثة: متاهة القراءة";
            document.getElementById('section-screen').classList.remove('hidden');
            return;
        } else {
            clearInterval(timerInterval);
            alert(`🏆 مبروك الفوز النهائي! أتممتِ جميع المراحل بنجاح. مجموع نقاطك: ${score}`);
            location.reload();
            return;
        }
    }
    
    const qData = questions[currentQ];
    let shuffledOptions = [...qData.o];
    shuffleArray(shuffledOptions);

    document.getElementById('section-title').innerText = `لوحة الأسئلة (السؤال ${currentQ + 1} من ${questions.length})`;
    document.getElementById('question').innerText = qData.q;
    
    const optionsDiv = document.getElementById('options');
    optionsDiv.innerHTML = "";
    
    shuffledOptions.forEach(opt => {
        const btn = document.createElement('button');
        btn.classList.add('opt-btn');
        btn.innerText = opt;
        btn.onclick = () => handleAnswer(opt);
        optionsDiv.appendChild(btn);
    });
}

function handleAnswer(choice) {
    const feedback = document.getElementById('feedback');
    const qData = questions[currentQ];

    const buttons = document.querySelectorAll('.opt-btn');
    buttons.forEach(b => b.disabled = true);

    if (choice === qData.a) {
        if (currentQ === 0 || currentQ === 1) {
            score += 5;
            feedback.innerText = "إجابة صحيحة! +5 نقاط ✨";
        } else {
            score += 3;
            feedback.innerText = "إجابة صحيحة! +3 نقاط 👍";
        }
        
        document.getElementById('score-display').innerText = `🌟 النقاط: ${score}`;
        feedback.style.color = "#50fa7b";

        pathIndex++;
        if (pathIndex >= pathCoords.length) pathIndex = pathCoords.length - 1;
        
        currentQ++;
        updatePositions();
        checkStatus();
        
        if (currentQ < questions.length) {
            setTimeout(loadQuestion, 1200);
        }
    } else {
        feedback.innerHTML = `إجابة خاطئة! الوحش يتقدم نحوِك! ❌`;
        feedback.style.color = "#ff5555";

        monsterIndex++; 
        currentQ++;     
        updatePositions();
        checkStatus();

        if (currentQ < questions.length) {
            setTimeout(loadQuestion, 1500);
        } else {
            setTimeout(loadQuestion, 1500);
        }
    }
}

function updatePositions() {
    document.querySelectorAll('.cell.path').forEach(cell => {
        cell.style.backgroundColor = ""; 
    });

    document.querySelectorAll('.player-img, .monster-img').forEach(el => el.remove());
    
    const pPos = pathCoords[pathIndex] || pathCoords[pathCoords.length - 1];
    const pCell = document.getElementById(`cell-${pPos.y}-${pPos.x}`);
    if (pCell) {
        pCell.style.backgroundColor = "#ffffff"; 
        const pImg = document.createElement('img');
        pImg.src = selectedHeroImg; 
        pImg.classList.add('player-img');
        pCell.appendChild(pImg);
    }

    const mPos = pathCoords[Math.min(monsterIndex, pathCoords.length - 1)];
    const mCell = document.getElementById(`cell-${mPos.y}-${mPos.x}`);
    if (mCell) {
        const mImg = document.createElement('img');
        mImg.src = "https://img.icons8.com/color/160/monster-face.png";
        mImg.classList.add('monster-img');
        mCell.appendChild(mImg);
    }
}

function checkStatus() {
    if (monsterIndex >= pathIndex) {
        monsterIndex = 0; 
        score -= 3; 
        document.getElementById('score-display').innerText = `🌟 النقاط: ${score}`;
        updatePositions();
        const feedback = document.getElementById('feedback');
        feedback.innerHTML = "⚠️ أمسك بك الوحش وأكلك! عاد إلى البداية وتم خصم 3 نقاط!";
        feedback.style.color = "#ff5555";
    }
}